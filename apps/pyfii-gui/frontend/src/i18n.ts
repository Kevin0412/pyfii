export type MessageKey = keyof typeof messages.en;

export function text(locale: LocaleMode, key: MessageKey): string {
  return messages[locale][key] ?? messages.en[key];
}

export function safetyCategoryLabel(locale: LocaleMode, category: SafetyCategory, short = false): string {
  const labels = categoryMessages[locale][category] ?? categoryMessages.en[category];
  return short ? labels.short : labels.label;
}
